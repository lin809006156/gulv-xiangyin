let s = fs.readFileSync(FILE, 'utf8');
let filled = 0;
const notFound = [];

Object.keys(REASONS).forEach((name) => {
  const reason = REASONS[name];
  // 定位该物象条目，替换其空的 reason 字段
  const re = new RegExp(
    "('" + name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + "':\\s*\\{[^}]*?reason:\\s*)'([^']*)'",
    'g'
  );
  let hit = false;
  s = s.replace(re, (m, p1, old) => {
    hit = true;
    if (old && old.trim()) return m;      // 已有理由，不覆盖
    filled++;
    return p1 + "'" + reason + "'";
  });
  if (!hit) notFound.push(name);
});

fs.writeFileSync(FILE, s);
console.log(`已补写取象之理 ${filled} 条`);
if (notFound.length) {
  console.log('未匹配到（请检查名称）：' + notFound.join('、'));
  process.exit(1);
}
